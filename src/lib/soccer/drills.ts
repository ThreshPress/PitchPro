const LEVELS: Level[] = ["easy", "standard", "hard"];

export function pickDrill(args: {
  slot: Slot;
  theme: SkillKey;
  age: number;
  level: Level;
  gk: boolean;
  salt: number;
  exclude?: string[];
}): Drill {
  let pool = DRILLS.filter(
    (d) => d.slots.includes(args.slot) && args.age >= d.minAge && args.age <= d.maxAge,
  );

  if (!args.gk) pool = pool.filter((d) => !d.gk);

  if (args.gk && (args.slot === "technical" || args.slot === "mastery" || args.slot === "finish")) {
    const gkPool = pool.filter((d) => d.gk);
    if (gkPool.length) pool = gkPool;
  } else if (args.gk) {
    pool = pool.filter((d) => !d.gk);
  }

  if (args.slot === "technical" || args.slot === "game" || args.slot === "finish") {
    const themed = pool.filter((d) => d.themes.includes(args.theme));
    if (themed.length) pool = themed;
  }

  pool = closestLevel(pool, args.level);
  if (args.exclude?.length) {
    const fresh = pool.filter((d) => !args.exclude?.includes(d.id));
    if (fresh.length) pool = fresh;
  }
  if (!pool.length) return FALLBACK;
  return pool[args.salt % pool.length] ?? FALLBACK;
}

function closestLevel(pool: Drill[], level: Level): Drill[] {
  if (!pool.length) return pool;
  if (pool.some((d) => d.level === level)) return pool.filter((d) => d.level === level);
  const idx = LEVELS.indexOf(level);
  for (let dist = 1; dist <= 2; dist += 1) {
    for (const next of [idx - dist, idx + dist]) {
      if (next < 0 || next >= LEVELS.length) continue;
      const hit = pool.filter((d) => d.level === LEVELS[next]);
      if (hit.length) return hit;
    }
  }
  return pool;
}
